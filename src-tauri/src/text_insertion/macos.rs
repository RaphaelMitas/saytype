const ANSI_V_KEYCODE: u16 = 9;
const LEFT_COMMAND_KEYCODE: u16 = 55;
const KEY_HOLD: Duration = Duration::from_millis(15);
// slowest measured read after ⌘V: 173 ms on a busy Chrome page
const RESTORE_AFTER: Duration = Duration::from_secs(1);
const MAX_RESTORE_BYTES: usize = 32 << 20;
// nspasteboard.org markers: clipboard managers skip items carrying them.
const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";
const MARKER_TYPES: [&str; 3] = [
    TRANSIENT_TYPE,
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

static PASTE: Mutex<()> = Mutex::new(());

type Snapshot = Vec<Vec<(Retained<NSString>, Retained<NSData>)>>;

/// Waits ~1 s before restoring the clipboard; never call on the main thread.
pub fn insert_text(app: &tauri::AppHandle, text: &str) -> Result<(), String> {
    let _serialized = PASTE.lock().unwrap_or_else(|e| e.into_inner());
    let pasteboard = NSPasteboard::generalPasteboard();

    // CGEventPost drops events silently without Accessibility
    let events = if super::check_accessibility_permission() {
        command_v_events(command_v_keycode(app))
    } else {
        Err("Accessibility permission missing".to_string())
    };
    let events = match events {
        Ok(events) => events,
        Err(e) => {
            write_transcript(&pasteboard, text, false);
            return Err(format!("{e}; transcript left on the clipboard"));
        }
    };

    let snapshot = snapshot(&pasteboard);
    write_transcript(&pasteboard, text, true);
    let ours = pasteboard.changeCount();
    for event in events {
        event.post(CGEventTapLocation::Session);
        thread::sleep(KEY_HOLD);
    }
    thread::sleep(RESTORE_AFTER);

    if let Some(snapshot) = snapshot {
        if pasteboard.changeCount() == ours {
            pasteboard.clearContents();
            write_items(&pasteboard, &restore_items(snapshot));
        }
    }
    Ok(())
}

/// None if the clipboard had items but none fit the budget, so the transcript stays.
fn snapshot(pasteboard: &NSPasteboard) -> Option<Snapshot> {
    let originals = pasteboard.pasteboardItems().unwrap_or_default();
    let mut bytes = 0;
    let mut items = Vec::new();
    for item in originals.iter() {
        let mut entries = Vec::new();
        for kind in item.types().iter() {
            if is_file_promise(&kind) {
                continue;
            }
            let Some(data) = item.dataForType(&kind) else {
                continue;
            };
            // Dropping only this type lets a huge copy still keep its text.
            if bytes + data.length() > MAX_RESTORE_BYTES {
                continue;
            }
            bytes += data.length();
            entries.push((kind, data));
        }
        if !entries.is_empty() {
            items.push(entries);
        }
    }
    (!items.is_empty() || originals.is_empty()).then_some(items)
}

// Promised files are produced by the source app on demand and can't be written back.
fn is_file_promise(kind: &NSString) -> bool {
    let kind = kind.to_string();
    kind.starts_with("com.apple.pasteboard.promised-")
        || kind == "com.apple.NSFilePromiseItemMetaData"
}

/// While pasting it is hidden from clipboard managers and other devices;
/// left behind for a manual ⌘V it is an ordinary copy.
fn write_transcript(pasteboard: &NSPasteboard, text: &str, pasting: bool) {
    let item = NSPasteboardItem::new();
    item.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString });
    if pasting {
        pasteboard.prepareForNewContentsWithOptions(NSPasteboardContentsOptions::CurrentHostOnly);
        for marker in MARKER_TYPES {
            item.setData_forType(&NSData::new(), &NSString::from_str(marker));
        }
    } else {
        pasteboard.clearContents();
    }
    write_items(pasteboard, &[item]);
}

fn restore_items(snapshot: Snapshot) -> Vec<Retained<NSPasteboardItem>> {
    snapshot
        .into_iter()
        .map(|entries| {
            let item = NSPasteboardItem::new();
            for (kind, data) in entries {
                item.setData_forType(&data, &kind);
            }
            // Clipboard managers already logged this copy once.
            item.setData_forType(&NSData::new(), &NSString::from_str(TRANSIENT_TYPE));
            item
        })
        .collect()
}

fn write_items(pasteboard: &NSPasteboard, items: &[Retained<NSPasteboardItem>]) {
    if items.is_empty() {
        return;
    }
    let objects: Vec<&ProtocolObject<dyn NSPasteboardWriting>> = items
        .iter()
        .map(|item| ProtocolObject::from_ref(&**item))
        .collect();
    pasteboard.writeObjects(&NSArray::from_slice(&objects));
}

fn command_v_events(v_keycode: u16) -> Result<Vec<CGEvent>, String> {
    let source = CGEventSource::new(CGEventSourceStateID::CombinedSessionState)
        .map_err(|_| "Failed to create event source".to_string())?;
    let command = CGEventFlags::CGEventFlagCommand;
    [
        (LEFT_COMMAND_KEYCODE, true, command),
        (v_keycode, true, command),
        (v_keycode, false, command),
        (LEFT_COMMAND_KEYCODE, false, CGEventFlags::CGEventFlagNull),
    ]
    .into_iter()
    .map(|(keycode, down, flags)| {
        let event = CGEvent::new_keyboard_event(source.clone(), keycode, down)
            .map_err(|_| "Failed to create key event".to_string())?;
        event.set_flags(flags);
        Ok(event)
    })
    .collect()
}

// Dvorak types "." on keycode 9, and the TIS layout APIs only work on the main thread.
fn command_v_keycode(app: &tauri::AppHandle) -> u16 {
    let (tx, rx) = mpsc::sync_channel(1);
    if app
        .run_on_main_thread(move || {
            let _ = tx.send(layout_command_v_keycode());
        })
        .is_err()
    {
        return ANSI_V_KEYCODE;
    }
    rx.recv_timeout(Duration::from_millis(500))
        .ok()
        .flatten()
        .unwrap_or(ANSI_V_KEYCODE)
}

#[link(name = "Carbon", kind = "framework")]
extern "C" {
    fn TISCopyCurrentKeyboardLayoutInputSource() -> *const c_void;
    fn TISGetInputSourceProperty(source: *const c_void, key: *const c_void) -> CFDataRef;
    static kTISPropertyUnicodeKeyLayoutData: *const c_void;
    fn UCKeyTranslate(
        layout: *const u8,
        keycode: u16,
        action: u16,
        modifier_state: u32,
        keyboard_type: u32,
        options: u32,
        dead_key_state: *mut u32,
        max_length: usize,
        actual_length: *mut usize,
        unicode: *mut u16,
    ) -> i32;
    fn LMGetKbdType() -> u8;
}

fn layout_command_v_keycode() -> Option<u16> {
    const KEY_ACTION_DISPLAY: u16 = 3;
    const COMMAND_MODIFIER_STATE: u32 = 1;
    const NO_DEAD_KEYS: u32 = 1;

    unsafe {
        let source = TISCopyCurrentKeyboardLayoutInputSource();
        if source.is_null() {
            return None;
        }
        let layout_data = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData);
        let layout = if layout_data.is_null() {
            std::ptr::null()
        } else {
            CFDataGetBytePtr(layout_data)
        };
        let keycode = (!layout.is_null())
            .then(|| {
                let keyboard_type = u32::from(LMGetKbdType());
                (0..128u16).find(|&keycode| {
                    let mut dead_key_state = 0;
                    let mut chars = [0u16; 4];
                    let mut length = 0;
                    let status = UCKeyTranslate(
                        layout,
                        keycode,
                        KEY_ACTION_DISPLAY,
                        COMMAND_MODIFIER_STATE,
                        keyboard_type,
                        NO_DEAD_KEYS,
                        &mut dead_key_state,
                        chars.len(),
                        &mut length,
                        chars.as_mut_ptr(),
                    );
                    status == 0 && length == 1 && chars[0] == u16::from(b'v')
                })
            })
            .flatten();
        CFRelease(source);
        keycode
    }
}
